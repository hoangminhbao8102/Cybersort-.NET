public class Method
{
    /// <summary>
    /// Hàm tính tổng nhận vào 2 số a vả b trả về kết quả là tổng 2 số
    /// </summary>
    /// <param name="a">Tham số thứ 1 : int</param>
    /// <param name="b">Tham số thứ 2 : int</param>
    /// <returns>Tổng 2 số</returns>
    public static int TinhTong(int a, int b) // a, b: input của hàm
    {
        int tong = 0; // output chưa xử lý
        // Process
        tong = a + b;

        return tong; // output
    }
}